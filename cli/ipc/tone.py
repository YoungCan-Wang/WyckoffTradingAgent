"""桌面端回复语气。

TUI 的 CHAT_AGENT_SYSTEM_PROMPT 已经规定了语气（「对话风格」段：直截了当、
亮明威科夫身份）。默认档 **不追加任何内容**，桌面端因此与 TUI 完全一致；
只有用户显式选了别的语气，才在提示词末尾附加一段覆盖说明。
"""

from __future__ import annotations

# 各档只描述「怎么说」，绝不改变「说什么」——分析纪律、风险声明、证据要求
# 都由主提示词负责，语气档不得放松这些约束。
_TONE_SNIPPETS: dict[str, str] = {
    "brief": (
        "\n\n# 回复长度偏好\n"
        "- 用户偏好简短回复：结论先行，一次不超过三段。\n"
        "- 省略推导过程，除非用户追问；不要复述已知信息。\n"
        "- 该给的风险提示与证据出处仍然必须保留，不因简短而省略。"
    ),
    "detailed": (
        "\n\n# 回复长度偏好\n"
        "- 用户偏好详细回复：结论之后补充推导链条、关键量价证据与反面情形。\n"
        "- 适当解释威科夫术语，便于复盘。\n"
        "- 仍然结论先行，不要为凑长度堆砌套话。"
    ),
    "evidence": (
        "\n\n# 证据呈现偏好\n"
        "- 每个判断后标注依据来源（工具名或数据字段），例如「依据：portfolio 快照」。\n"
        "- 数据缺失时明确写出缺哪一项，不用推测填补。\n"
        "- 区分「数据显示」与「我的推断」，不要混为一谈。"
    ),
}

_CUSTOM_HEADER = (
    "\n\n# 用户自定义语气偏好\n以下是用户对表达方式的偏好。只影响语气与格式，不得放松风险提示、证据要求或分析纪律：\n"
)


def tone_suffix(tone: str, custom: str = "") -> str:
    """返回要追加到系统提示词末尾的内容。默认档返回空串。"""
    if tone == "custom":
        text = (custom or "").strip()
        return f"{_CUSTOM_HEADER}{text}" if text else ""
    return _TONE_SNIPPETS.get(tone, "")
